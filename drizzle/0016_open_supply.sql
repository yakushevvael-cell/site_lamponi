-- Поставка Wildberries открывается на упаковке, а не в конце дня.
--
-- WB отдаёт стикер сборочного задания только после того, как задание попало
-- в поставку: у задания в статусе new этикетки не существует вовсе. Поэтому
-- поставка заводится при первой подготовке этикетки и живёт в статусе open,
-- пока «Оформить поставку» её не закроет.
--
-- Открытая поставка у задания может быть только одна: иначе часть заданий
-- уедет в одну поставку, часть в другую, и на приёмке это не собрать.
CREATE UNIQUE INDEX `supply_open_task_unique` ON `supplies` (`task_id`) WHERE `status` = 'open';
