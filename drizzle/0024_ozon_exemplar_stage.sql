-- Проверка УИН в Ozon как отдельный этап подготовки этикетки.
--
-- Раньше вся цепочка (передать УИН → дождаться проверки → собрать → забрать
-- этикетку) шла внутри одного запроса, а на ожидание отводилось 9 секунд.
-- Проверка УИН у Ozon асинхронная и идёт минутами, поэтому отправление почти
-- всегда объявлялось ошибочным, а следующая попытка передавала УИН заново и
-- обнуляла проверку. Теперь между попытками сохраняется состояние.
--
-- `exemplar_status` — последний ответ Ozon (`validation_in_process`,
-- `update_available` и т. д.), `note` — то же человеческим языком для стола.
-- Ошибкой это не является, поэтому `error` при ожидании остаётся пустым.
ALTER TABLE `shipment_labels` ADD `exemplar_status` text;--> statement-breakpoint
ALTER TABLE `shipment_labels` ADD `note` text;--> statement-breakpoint
-- Номера отправлений, которые Ozon вернул после сборки: многотоварное
-- отправление делится на несколько, и без этих номеров повторный заход за
-- этикеткой начинал бы всю цепочку с экземпляров — по уже собранному
-- отправлению это заведомо ошибка.
ALTER TABLE `shipment_labels` ADD `ship_postings` text;
